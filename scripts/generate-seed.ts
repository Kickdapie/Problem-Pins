// Writes supabase/seed.sql from the demo's sample data, so a fresh local or staging
// database starts with the same West Side District as the demo.
//
//   npm run db:seed-sql        (then `supabase db reset` to load it locally)
//
// Counts in the sample (votes, votesThisWeek, following, confirmedFixed, notFixed,
// duplicatesMerged) become records: anonymous votes, follows and confirmations spread over
// the issue's life, and merged duplicate issues. The demo's analytics events come along too.
// Dates are written relative to the day the seed runs: the demo's "today" (DEMO_TODAY)
// becomes today in New York.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEMO_DISTRICT, DEMO_SCAN_POINTS } from '../src/data/demoDistrict.ts';
import { DEMO_EVENTS } from '../src/data/demoEvents.ts';
import { SAMPLE_ISSUES } from '../src/data/sampleData.ts';
import type { Issue } from '../src/data/types.ts';

// Same value as DEMO_TODAY in src/lib/format.ts (that module reads Vite env, so it can't be imported here).
const DEMO_TODAY = '2026-10-14';

/** Duplicate reports behind PP-2402's `duplicatesMerged: 5`, so the count comes from records. */
const MERGED_DUPLICATES: { id: string; into: string; title: string; createdAt: string; via?: string }[] = [
  { id: 'PP-2403', into: 'PP-2402', title: 'Street light out on W 16th St', createdAt: '2026-09-28' },
  { id: 'PP-2405', into: 'PP-2402', title: 'Dark stretch of W 16th St at night', createdAt: '2026-09-29' },
  { id: 'PP-2406', into: 'PP-2402', title: 'Lamp post not working near 10th Ave', createdAt: '2026-09-29' },
  { id: 'PP-2408', into: 'PP-2402', title: 'No lights on W 16th between 9th and 10th', createdAt: '2026-09-30' },
  { id: 'PP-2411', into: 'PP-2402', title: 'Broken street lamp, W 16th St', createdAt: '2026-10-01', via: 'QR · Community noticeboard Q-12' },
];

const DAY = 86400000;
const daysAgo = (date: string) => Math.round((Date.parse(DEMO_TODAY) - Date.parse(date)) / DAY);

function lit(value: unknown): string {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value)) return value.length ? `array[${value.map(lit).join(', ')}]` : `'{}'`;
  if (typeof value === 'object') return `${lit(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const ago = (date: string, minutes = 0) => `private.seed_ago(${daysAgo(date)}${minutes ? `, ${minutes}` : ''})`;

/** An instant from demoEvents.ts (New York time, EDT for the whole demo window) as a seed time. */
function agoInstant(iso: string) {
  const local = new Date(Date.parse(iso) - 4 * 3600000);
  return ago(local.toISOString().slice(0, 10), local.getUTCHours() * 60 + local.getUTCMinutes() - 12 * 60);
}

const d = DEMO_DISTRICT;
const out: string[] = [];
const sql = (s: string) => out.push(s);

sql(`-- Generated by scripts/generate-seed.ts from src/data/sampleData.ts and src/data/demoDistrict.ts.
-- Don't edit by hand: change the sample data and run \`npm run db:seed-sql\`.
--
-- Sample data for the fictional ${d.name}. Fine for local and staging, never for production.
-- Dates are relative to the day it runs (${DEMO_TODAY} in the sample = today in New York).
-- Meant for an empty database: \`supabase db reset\` locally, or once on a new staging project:
--   psql "$DB_URL" --single-transaction -v ON_ERROR_STOP=1 -f supabase/seed.sql

-- Don't send a Realtime ping for every seeded row.
set pp.seeding = 'on';

-- Seed-only helpers, dropped at the end.
-- Noon in New York, \`days\` days ago (plus \`minutes\`), never in the future.
create function private.seed_ago(days integer, minutes integer default 0)
returns timestamptz
language sql
as $$
  select least(
    now(),
    ((((now() at time zone 'America/New_York')::date - days) + time '12:00') + make_interval(mins => minutes))
      at time zone 'America/New_York'
  );
$$;

-- \`n\` timestamps spread from \`from_days\` ago to \`to_days\` ago.
create function private.seed_spread(n integer, from_days integer, to_days integer)
returns setof timestamptz
language sql
as $$
  select private.seed_ago(from_days - (g * (from_days - to_days + 1)) / n, (g * 37) % 600)
  from generate_series(0, n - 1) g;
$$;

-- The inserts run inside one block because \`supabase db reset\` prepares every top-level
-- statement before running any, and the helpers above don't exist yet at that point.
do $seed$
begin

if exists (select 1 from public.districts where id = ${lit(d.id)}) then
  raise exception 'The sample district ${d.id} is already loaded.';
end if;
`);

sql(`insert into public.districts (id, name, area, center_lat, center_lng, zoom, boundary, categories, teams, rules, contact_email)
values (
  ${lit(d.id)}, ${lit(d.name)}, ${lit(d.area)}, ${d.center.lat}, ${d.center.lng}, ${d.zoom},
  ${lit(d.boundary ?? null)},
  ${lit(d.categories)},
  ${lit(d.teams)},
  ${lit(d.rules)},
  ${lit(d.contactEmail ?? null)}
);
`);

function issueRow(i: Issue & { mergedInto?: string }) {
  return `  (${[
    lit(i.id),
    lit(d.id),
    lit(i.title),
    lit(i.description),
    lit(i.category),
    lit(i.status),
    i.lat,
    i.lng,
    lit(i.locationLabel),
    lit(i.locationDetail ?? null),
    lit(i.via),
    lit(i.owner),
    lit(i.agency ?? null),
    lit(i.mergedInto ?? null),
    i.fixedOn ? ago(i.fixedOn, 1) : 'null',
    ago(i.createdAt),
  ].join(', ')})`;
}

const issueColumns =
  'id, district_id, title, description, category, status, lat, lng, location_label, location_detail, via, owner, agency, merged_into, fixed_at, created_at';

sql(`insert into public.issues (${issueColumns}) values
${SAMPLE_ISSUES.map(issueRow).join(',\n')};
`);

const target = (id: string) => SAMPLE_ISSUES.find((i) => i.id === id)!;
const duplicates = MERGED_DUPLICATES.map((m) => {
  const into = target(m.into);
  return {
    ...into,
    id: m.id,
    title: m.title,
    description: '',
    status: 'open' as const,
    createdAt: m.createdAt,
    owner: null,
    agency: undefined,
    locationDetail: undefined,
    fixedOn: undefined,
    via: m.via ?? 'the map',
    mergedInto: m.into,
    updates: [],
    history: [
      { date: m.createdAt, text: 'Pinned on the map' },
      { date: m.createdAt, text: `Merged into ${m.into}` },
    ],
  };
});

sql(`-- Duplicate reports already merged (their votes and follows now count on the issue they went into).
insert into public.issues (${issueColumns}) values
${duplicates.map(issueRow).join(',\n')};
`);

const allIssues = [...SAMPLE_ISSUES, ...duplicates];

const updates = allIssues.flatMap((i) =>
  i.updates.map(
    (u, n) =>
      `  (${[lit(i.id), lit(u.role), lit(u.author), lit(u.text), ago(u.date, 10 + n)].join(', ')})`,
  ),
);
sql(`insert into public.issue_updates (issue_id, role, author_name, text, created_at) values
${updates.join(',\n')};
`);

const history = allIssues.flatMap((i) => i.history.map((h, n) => `  (${[lit(i.id), lit(h.text), ago(h.date, n)].join(', ')})`));
sql(`insert into public.issue_history (issue_id, text, created_at) values
${history.join(',\n')};
`);

const requests = SAMPLE_ISSUES.filter((i) => i.cityRequest).map((i) => {
  const r = i.cityRequest!;
  return `  (${[
    lit(i.id),
    lit(r.sr),
    lit(r.agency),
    lit(r.routedTo),
    ago(r.sentOn, 2),
    lit(r.sentBy),
    r.lastFollowUp ? ago(r.lastFollowUp, 3) : 'null',
  ].join(', ')})`;
});
sql(`insert into public.city_requests (issue_id, sr, agency, routed_to, sent_at, sent_by_name, last_follow_up_at) values
${requests.join(',\n')};
`);

// Votes: `votesThisWeek` of them in the last 7 days, the rest between the day it was
// pinned and a week ago. A problem pinned less than a week ago has all its votes this week.
sql('-- Anonymous votes, follows and fix confirmations behind the sample counts.');
for (const i of SAMPLE_ISSUES) {
  const age = daysAgo(i.createdAt);
  const recent = age <= 6 ? i.votes : Math.min(i.votesThisWeek, i.votes);
  const older = i.votes - recent;
  if (older > 0) sql(`insert into public.votes (issue_id, user_id, created_at) select ${lit(i.id)}, gen_random_uuid(), t from private.seed_spread(${older}, ${age}, 7) t;`);
  if (recent > 0) sql(`insert into public.votes (issue_id, user_id, created_at) select ${lit(i.id)}, gen_random_uuid(), t from private.seed_spread(${recent}, ${Math.min(age, 6)}, 0) t;`);
  if (i.following > 0) sql(`insert into public.follows (issue_id, user_id, created_at) select ${lit(i.id)}, gen_random_uuid(), t from private.seed_spread(${i.following}, ${age}, 0) t;`);
  if (i.confirmedFixed > 0 && i.fixedOn) {
    sql(`insert into public.fix_confirmations (issue_id, user_id, answer, created_at) select ${lit(i.id)}, gen_random_uuid(), 'yes', t from private.seed_spread(${i.confirmedFixed}, ${daysAgo(i.fixedOn)}, 0) t;`);
  }
  // From the day after the fix, so they count as answers to it (see `not_fixed` in get_snapshot).
  if (i.notFixed > 0 && i.fixedOn) {
    sql(`insert into public.fix_confirmations (issue_id, user_id, answer, created_at) select ${lit(i.id)}, gen_random_uuid(), 'no', t from private.seed_spread(${i.notFixed}, ${Math.max(daysAgo(i.fixedOn) - 1, 0)}, 0) t;`);
  }
}
sql('');

const events = DEMO_EVENTS.map(
  (e) =>
    `  (${[lit(d.id), lit(e.name), lit(e.issueId ?? null), lit(e.scanCode ?? null), lit(e.props ?? null), agoInstant(e.at)].join(', ')})`,
);
sql(`-- The demo's sample analytics (src/data/demoEvents.ts), so the dashboard and Reports have figures to show.
insert into public.events (district_id, name, issue_id, scan_code, props, at) values
${events.join(',\n')};
`);

sql(`insert into public.scan_points (district_id, code, name, detail, lat, lng, issue_id) values
${DEMO_SCAN_POINTS.map((p) => `  (${[lit(d.id), lit(p.code), lit(p.name), lit(p.detail), p.lat, p.lng, lit(p.issueId ?? null)].join(', ')})`).join(',\n')};

end;
$seed$;

drop function private.seed_spread(integer, integer, integer);
drop function private.seed_ago(integer, integer);
reset pp.seeding;
`);

const file = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(file, out.join('\n'));
console.log(`Wrote ${file}: ${allIssues.length} issues (${duplicates.length} merged duplicates).`);
